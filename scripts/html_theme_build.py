# imports
import html
import re
from datetime import date
from .util import ROOT, parse_date, pretty_month_year, pretty_day_month_year

# output page and main page
HTML_THEME_OUT = ROOT / "html" / "index.html"
INDEX_HTML = ROOT / "index.html"

# image width in pixels
IMAGE_WIDTH = 150

# talk category labels
CATEGORY_LABELS = {"invited": "Invited Talks", "lectures": "Lecture Series & Schools", "contributed": "Contributed Talks"}

# section text
SECTION_BLURBS = {"contact": 'Reach me at <a href="mailto:gambhirb@ucmail.uc.edu">gambhirb@ucmail.uc.edu</a>. Full history is in the <a href="/assets/pdf/rikab_CV.pdf">CV</a>.', "featured": "A few papers I'd recommend starting with.", "stats": 'Live from <a href="https://inspirehep.net">INSPIRE-HEP</a>. Refreshed weekly.', "talks": "Selected presentations. ★ marks my recommended version of a given talk.", "software": "Open-source libraries I develop or maintain. Most have an associated paper."}

# banner and head for the generated page
GEN_HEADER_HTML = "<!-- AUTO-GENERATED by scripts/build.py from content.yaml -- DO NOT EDIT. -->\n"
PAGE_HEAD = '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n<title>Rikab Gambhir</title>\n</head>\n<body>'


# site-root path
def site_path(href):

    # root-relative href
    if href.startswith(("http:", "https:", "mailto:", "/", "#")):
        return href
    return "/" + href.removeprefix("./")


# escape plain text
def escape_text(value):

    # escaped text
    return html.escape(str(value or ""))


# drop bold
def strip_bold(fragment):

    # unbolded fragment
    return fragment.replace("<strong>", "").replace("</strong>", "")


# one hyperlink
def link(label, href):

    # anchor tag
    return f'<a href="{html.escape(site_path(href))}">{escape_text(label)}</a>'


# one image
def image(src):

    # image tag
    return f'<p><img src="{html.escape(site_path(src))}" width="{IMAGE_WIDTH}" alt=""></p>'


# related-talk label
def talk_label(talk):

    # date and where
    return pretty_day_month_year(parse_date(talk["date"])) + " · " + talk["where"]


# paper detail lines
def paper_details(paper, talks_by_id):

    # title, authors, date, flags
    details = [escape_text(paper["title"]), escape_text(paper["authors"]), pretty_month_year(parse_date(paper["date"]))]
    if paper["featured"] and not paper["joke"]:
        details.append("★")
    if paper["joke"]:
        details.append("🃏 April Fools")

    # links and citation count
    if paper["links"]:
        details.append(" | ".join(link(item["text"], item["href"]) for item in paper["links"]))
    if paper["citations"]:
        details.append(f'Citations: {paper["citations_total"]} total, {paper["citations_total_excl_self"]} excl. self')

    # tags and related talks
    if paper["tags"]:
        details.append("Tags: " + escape_text(", ".join(paper["tags"])))
    talk_links = [link(talk_label(talks_by_id[talk_id]), f"#talk-{talk_id}") for talk_id in paper["talks"] if talk_id in talks_by_id]
    if talk_links:
        details.append("Talks: " + " | ".join(talk_links))
    return details


# blurb, abstract, bibtex
def paper_text_blocks(paper):

    # blurb and abstract
    blocks = [f"<p>{escape_text(text)}</p>" for text in (paper["blurb"], paper["abstract"]) if text]

    # bibtex
    if paper["bibtex"]:
        blocks.append("<p>BibTeX:<br>\n" + escape_text(paper["bibtex"]).replace("\n", "<br>\n") + "</p>")
    return blocks


# one paper
def paper_block(paper, talks_by_id):

    # image, details, longer text
    blocks = [image(paper["img"])] if paper["img"] else []
    blocks.append(f'<p id="paper-{escape_text(paper["id"])}">' + "<br>\n".join(paper_details(paper, talks_by_id)) + "</p>")
    blocks.extend(paper_text_blocks(paper))
    return "\n".join(blocks)


# slides, video and paper links
def talk_link_list(talk, paper):

    # links that exist for this talk
    talk_links = []
    if talk["slides"]:
        talk_links.append(link("Slides", talk["slides"]))
    if talk["video"]:
        talk_links.append(link("Video", talk["video"]))
    if paper:
        talk_links.append(link("Paper: " + paper["title"], f'#paper-{paper["id"]}'))
    return talk_links


# one talk
def talk_block(talk, papers_by_id):

    # date, title, where, category, topic, featured
    details = [pretty_day_month_year(parse_date(talk["date"])) + ": " + escape_text(talk["title"])]
    label = CATEGORY_LABELS.get(talk["category"], talk["category"])
    if talk["topic"]:
        label += " · " + talk["topic"]
    details.append(escape_text(f'{talk["where"]} ({label})' if talk["where"] else label))
    if talk["featured"]:
        details.append("★")

    # links
    paper = papers_by_id.get(talk["paper"])
    talk_links = talk_link_list(talk, paper)
    if talk_links:
        details.append(" | ".join(talk_links))

    # abstract
    abstract = talk["abstract"] or (paper["blurb"] if paper else "")
    if abstract:
        details.append(escape_text(abstract))
    return f'<p id="talk-{escape_text(talk["id"])}">' + "<br>\n".join(details) + "</p>"


# one software package
def software_block(package, papers_by_id):

    # name, role, blurb, install command
    details = [escape_text(package["name"]) + (f' ({escape_text(package["role"])})' if package["role"] else "")]
    if package["blurb"]:
        details.append(escape_text(package["blurb"]))
    if package["install"]:
        details.append("$ " + escape_text(package["install"]))

    # github, homepage and paper links
    package_links = []
    if package["github"]:
        package_links.append(link("GitHub", package["github"]))
    if package["homepage"]:
        package_links.append(link("Homepage", package["homepage"]))
    paper = papers_by_id.get(package["paper"])
    if paper:
        package_links.append(link("Paper", f'#paper-{paper["id"]}'))
    if package_links:
        details.append(" | ".join(package_links))
    return "<p>" + "<br>\n".join(details) + "</p>"


# portrait, name, tagline, links, about
def about_blocks(about):

    # portrait, name, tagline, links
    blocks = [image(about["portrait"]), f'<p>Rikab Gambhir<br>\n{about["tagline"]}</p>']
    blocks.append("<p>" + " | ".join(link(item["text"], item["href"]) for item in about["links"]) + "</p>")

    # about paragraphs and contact line
    blocks.append("<p>About</p>")
    blocks.extend(f"<p>{strip_bold(paragraph)}</p>" for paragraph in about["paragraphs"])
    blocks.append(f'<p>{SECTION_BLURBS["contact"]}</p>')
    return blocks


# featured, research, citations, papers
def research_blocks(pubs_out, talks_by_id, author_cites, author_h):

    # featured research
    featured = [link(paper["title"], f'#paper-{paper["id"]}') for paper in pubs_out if paper["featured"] and not paper["joke"]]
    blocks = ["<p>" + "<br>\n".join(["Featured Research", SECTION_BLURBS["featured"]] + featured) + "</p>"]

    # research heading and citation totals
    blocks.append(f'<p>Research ({sum(not paper["joke"] for paper in pubs_out)})</p>')
    if author_cites and author_h:
        blocks.append(f'<p>Citations: {author_cites[-1]["total"]} total, {author_cites[-1]["excl_self"]} excl. self<br>\nh-index: {author_h[-1]["h"]}<br>\n{SECTION_BLURBS["stats"]}</p>')

    # every paper
    blocks.extend(paper_block(paper, talks_by_id) for paper in pubs_out)
    return blocks


# html mode page
def render_html_theme(about, pubs_out, talks_out, software_out, author_cites, author_h):

    # lookups for cross links
    papers_by_id = {paper["id"]: paper for paper in pubs_out}
    talks_by_id = {talk["id"]: talk for talk in talks_out}

    # about and research
    parts = [GEN_HEADER_HTML + PAGE_HEAD] + about_blocks(about) + research_blocks(pubs_out, talks_by_id, author_cites, author_h)

    # talks
    parts.append(f"<p>Talks ({len(talks_out)})</p>")
    parts.append(f'<p>{SECTION_BLURBS["talks"]}</p>')
    parts.extend(talk_block(talk, papers_by_id) for talk in talks_out)

    # software
    parts.append("<p>Software</p>")
    parts.append(f'<p>{SECTION_BLURBS["software"]}</p>')
    parts.extend(software_block(package, papers_by_id) for package in software_out)

    # footer
    parts.append(f'<p>&copy; 2022&ndash;{date.today().year} Rikab Gambhir.<br>\n{about["footer"]}</p>')
    return "\n\n".join(parts + ["</body>\n</html>"]) + "\n"


# write html/index.html
def write_html_theme(about, pubs_out, talks_out, software_out, author_cites, author_h):

    # make the folder and write the page
    HTML_THEME_OUT.parent.mkdir(exist_ok=True)
    HTML_THEME_OUT.write_text(render_html_theme(about, pubs_out, talks_out, software_out, author_cites, author_h))
    return HTML_THEME_OUT


# sync About paragraphs into index.html
def write_index_about(about):

    # find the markers
    page = INDEX_HTML.read_text()
    start = re.search(r"^([ \t]*)<!-- about:start -->\n", page, re.M)
    end = re.search(r"\n[ \t]*<!-- about:end -->", page)
    if not start or not end:
        raise ValueError("index.html is missing the about:start / about:end markers")

    # replace About block
    paragraphs = "\n".join(start.group(1) + f"<p>{paragraph}</p>" for paragraph in about["paragraphs"])
    INDEX_HTML.write_text(page[:start.end()] + paragraphs + page[end.start():])
